def _sections(tables_md: str) -> dict[int, str]:
    parts = re.split(r"^## (\d+)\. [^\n]*\n", tables_md, flags=re.M)
    return {int(parts[i]): parts[i + 1].strip() for i in range(1, len(parts), 2)}


def _blocks(text: str) -> dict[int, str]:
    found = re.findall(r"<!-- phase6:table (\d+) -->\n(.*?)\n<!-- /phase6:table -->", text, flags=re.S)
    return {int(n): body.strip() for n, body in found}


def _speed(summary, engine, key):
    return summary["speed"][engine][key]


def _assert_all_in(text: str, expected: list[str], what: str) -> None:
    missing = [s for s in expected if s not in text]
    assert not missing, f"{what} missing from the writeup: {missing}"


