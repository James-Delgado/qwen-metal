def test_energy_spreads_watts_and_idle_match_summary(text, summary):
    idle = summary["idle_baseline"]
    cycles = [c for e in an.ENGINES for c in summary["energy"][e]["cycles"]]
    watts = [c["implied_watts"] for c in cycles]
    sys_lo = min(100 * summary["energy"][e]["headline"]["systematic_fraction"] for e in an.ENGINES)
    sys_hi = max(100 * summary["energy"][e]["headline"]["systematic_fraction"] for e in an.ENGINES)
    expected = [f"{idle['watts']:.3f} W", f"{min(watts):.1f}–{max(watts):.1f} W", f"±{sys_lo:.1f}–{sys_hi:.1f}%"]
    for e, label in ENGINE_PROSE:
        h = summary["energy"][e]["headline"]
        half = (h["spread"][1] - h["spread"][0]) / 2 / h["mean_j_per_token"]
        expected.append(f"±{100 * half:.0f}% " + ("of the\n  mean for ours" if e == "ours" else f"for {label}"))
    _assert_all_in(text, expected, "energy spreads")


def test_low_start_cycles_are_each_engines_highest_reading(text, summary):
    """§4 / §7: the any-start deviation's measured consequence, stated as a claim
    the archive must support — the 60–61%-start cycle is each engine's maximum
    J/token AND maximum implied watts, and the writeup quotes those readings."""
    for e, label in ENGINE_PROSE:
        cycles = summary["energy"][e]["cycles"]
        low = [c for c in cycles if c["soc_start"] <= 61]
        assert len(low) == 1, e
        assert low[0]["net_joules_per_token"] == max(c["net_joules_per_token"] for c in cycles), e
        assert low[0]["implied_watts"] == max(c["implied_watts"] for c in cycles), e
        assert f"{label}\n{low[0]['net_joules_per_token']:.4f} at {low[0]['implied_watts']:.2f} W" in text \
            or f"{label} {low[0]['net_joules_per_token']:.4f} at {low[0]['implied_watts']:.2f} W" in text, e
    smallest_effect = _speed(summary, "llama", "decode_warm_median") - _speed(summary, "ours", "decode_warm_median")
    assert f"{smallest_effect:.2f}\ntok/s between llama.cpp and ours, exceeds it by more than {smallest_effect / summary['bookend_delta'] // 10 * 10:.0f}×" in text


def test_thermal_steps_and_plateau_bands_match_summary(text, summary):
    expected = []
    for e in an.ENGINES:
        s = summary["speed"][e]["sustained"]
        step = 100 * (1 - s["plateau_second_half_median"] / s["first_window"])
        expected.append(f"{s['first_window']:.2f} → {s['plateau_second_half_median']:.2f} (−{step:.0f}%)")
    for e, label in ENGINE_PROSE:
        cycles = [t for t in summary["thermal_cycles"] if t["file"].startswith(e)]
        plateaus = [t["plateau_second_half_median"] for t in cycles]
        steps = [100 * (1 - t["plateau_second_half_median"] / t["first_window"]) for t in cycles]
        expected += [f"{label} {min(plateaus):.1f}–{max(plateaus):.1f}", f"−{min(steps):.0f}% to −{max(steps):.0f}%"]
    _assert_all_in(text, expected, "thermal readings")


