"""Drift test for docs/writeup.md (task P6-6; docs/phases/phase-6.md D8).

The writeup's rule: every Phase 6 number is regenerated by
tools/phase6_analyze.py from benchmarks/phase6/, never typed (METHODOLOGY 4).
This file enforces it the way tests/test_priorities.py guards the backlog:

- every `<!-- phase6:table N -->` block equals section N of a FRESH analyzer
  run over the archive (the committed docs/writeup/tables.md + summary.json
  must equal that regeneration too);
- every inline headline number and every derived ratio in the prose is
  recomputed from the regenerated summary (or from the archived attribution
  exports) and must appear in the text at the precision the prose uses;
- the attribution exports quoted in §6 equal the archived files byte for byte;
- the nine D8 sections exist in order, the figures exist and are referenced,
  and the limitations / gaps / reproducibility sections name their required
  items (LD-1 and BW-1 as measured, the two FAILED gates, the pins).

Run: .venv/bin/python -m pytest tests/test_writeup.py -q
Deps: the repo-root .venv (tools/requirements-phase6.txt).
"""

