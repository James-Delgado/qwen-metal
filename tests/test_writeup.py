def test_every_analyzer_section_is_embedded_verbatim(text, tables):
    blocks, sections = _blocks(text), _sections(tables)
    assert set(blocks) == set(sections) == {1, 2, 3, 4, 5, 6, 7}
    for n in sorted(sections):
        assert blocks[n] == sections[n], f"writeup block {n} differs from a fresh regeneration"


