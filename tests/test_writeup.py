def _attribution(name: str) -> str:
    return (ARCHIVE / "speed" / "attribution" / name).read_text()


def _class_ms(export: str, cls: str) -> float:
    return float(re.search(rf"^\s+{re.escape(cls)}\s+([\d.]+) ms", export, flags=re.M).group(1))


def test_attribution_exports_are_quoted_verbatim(text):
    for name in ("ours-attribution-decode.txt", "ours-attribution-prefill.txt"):
        assert _attribution(name).strip() in text, name


def test_decode_weight_stream_rate_is_derived_from_the_attribution_export(text, summary):
    decode = _attribution("ours-attribution-decode.txt")
    streaming_ms = _class_ms(decode, "matvec") + _class_ms(decode, "head/tail")
    weight_bytes = summary["roofline_denominators"]["weight_bytes"]
    gbps = weight_bytes / (streaming_ms / 1000) / 1e9
    record = summary["roofline_denominators"]["triad_of_record_gbps"]
    expected = [f"{streaming_ms:.2f} ms", f"{weight_bytes:,} B ÷ {streaming_ms:.2f} ms = {gbps:.1f} GB/s",
                f"≈{100 * gbps / record:.0f}%", f"≈{weight_bytes / record / 1e6:.1f} ms"]
    _assert_all_in(text, expected, "decode stream-rate derivation")


def test_prefill_tflops_are_derived_from_the_attribution_export(text, summary):
    prefill = _attribution("ours-attribution-prefill.txt")
    gemm_ms = _class_ms(prefill, "gemm")
    flops = 2 * PREFILL_TOKENS * LAYER_PARAMS
    expected = [f"{LAYER_PARAMS:,} layer parameters = {flops / 1e12:.2f} TFLOP", f"{gemm_ms:.2f} ms",
                f"= {flops / (gemm_ms / 1000) / 1e12:.3f}"]
    for e in ("mlx", "llama"):
        span = PREFILL_TOKENS / _speed(summary, e, "prefill_warm_median")
        expected += [f"{span:.3f} s", f"≥ {flops / span / 1e12:.2f}"]
    _assert_all_in(text, expected, "prefill TFLOPS derivation")


