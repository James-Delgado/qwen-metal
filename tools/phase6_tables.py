"""Markdown tables for the Phase 6 analyzer (tools/phase6_analyze.py; task P6-3).

Renders a `Report` into the tables the writeup (docs/writeup.md, P6-6) pastes
or includes verbatim. A dash or a "REFUSED: …" cell means no headline value
exists — the analyzer never averages around a refusal, and this module never
computes a number of its own.
"""

from __future__ import annotations

import phase6_analyze as an
from phase6_analyze import CONSTANT_29_4, ENGINE_LABELS, ENGINES, SUCCESS_RATIO


def _fmt(value, digits=2, unit="") -> str:
    return "—" if value is None else f"{value:.{digits}f}{unit}"


def render_tables(r: an.Report) -> str:
    out = ["# Phase 6 — regenerated tables", "",
           f"Generated by tools/phase6_analyze.py from the archive; sessions: "
           f"{', '.join(f'{k} = {v.get('round')!r} (iOS {v.get('ios_build')})' for k, v in r.manifest.get('sessions', {}).items())}.",
           "Every value below is regenerated; a dash or a refusal means no headline value exists.", ""]
    out += _headline_table(r) + _verdict_section(r) + _sustained_table(r) + _energy_tables(r)
    out += _bandwidth_section(r) + _roofline_section(r) + _refusal_ledger(r)
    return "\n".join(out) + "\n"


def _headline_table(r: an.Report) -> list[str]:
    rows = ["## 1. Headline table (speed session)", "",
            "| engine | decode tok/s, warm burst (window median, n) | decode tok/s, cold (window) | prefill tok/s, warm (span median, n, tokens) | sustained plateau (2nd-half median) | phys_footprint (Xcode gauge) | net J/token (mean, n) |",
            "|---|---|---|---|---|---|---|"]
    for e in ENGINES:
        s, en = r.speed[e], r.energy[e]
        fp = ", ".join(f"{k} {v:.1f} MB" for k, v in s.footprint_mb.items()) or "—"
        sus = _fmt(s.sustained.plateau_second_half_median) if s.sustained else "—"
        energy = (f"{en.headline.mean_j_per_token:.4f} (n={en.headline.n})" if en.headline
                  else "REFUSED: " + (en.refusals[0] if en.refusals else "no valid cycles"))
        rows.append(f"| {ENGINE_LABELS[e]} | {_fmt(s.decode_warm.median)} (n={s.decode_warm.n}) | {_fmt(s.decode_cold.median)} | "
                    f"{_fmt(s.prefill_warm.median)} (n={s.prefill_warm.n}, {s.prefill_warm.token_count or '—'} tok) | {sus} | {fp} | {energy} |")
    rows.append("")
    return rows


def _verdict_section(r: an.Report) -> list[str]:
    v = r.verdict
    lines = ["## 2. Success-metric verdict (PLAN formula) and tripwires", ""]
    if v.met is None:
        lines.append("Verdict: REFUSED — " + "; ".join(v.refusals))
    else:
        lines.append(f"ours {v.ours_median:.2f} ÷ MLX {v.mlx_median:.2f} = {v.ratio:.3f} vs ≥ {SUCCESS_RATIO} ⇒ "
                     f"**{'MET' if v.met else 'NOT MET'}** (the committed {CONSTANT_29_4} tok/s constant reported alongside)")
    for t in r.tripwires.values():
        verdict = "—" if t.passed is None else ("PASS" if t.passed else "FAIL")
        lines.append(f"- tripwire {t.name} ≥ {t.floor:g}: {_fmt(t.value)} ⇒ {verdict}")
    lines.append(f"- bookend delta (close − open, window tok/s): {_fmt(r.bookend_delta)}")
    lines.append("")
    return lines


def _sustained_table(r: an.Report) -> list[str]:
    rows = ["## 3. Sustained 5-min loops (speed session)", "",
            "| engine | generations | first window tok/s | last window tok/s | 2nd-half median | minutes | elapsed basis |", "|---|---|---|---|---|---|---|"]
    for e in ENGINES:
        s = r.speed[e].sustained
        if s is None:
            rows.append(f"| {ENGINE_LABELS[e]} | — | — | — | — | — | — |")
            continue
        rows.append(f"| {ENGINE_LABELS[e]} | {s.generations} | {_fmt(s.first_window)} | {_fmt(s.last_window)} | "
                    f"{_fmt(s.plateau_second_half_median)} | {_fmt(s.minutes, 1)} | {s.basis} |")
    rows.append("")
    return rows


def _energy_tables(r: an.Report) -> list[str]:
    rows = ["## 4. Energy per token (energy round)", "",
            "| engine | cycle | health % | SoC start→end | ΔSoC | cycle wall s | tokens | gross J | implied W | idle ΔSoC (scaled) | net J | net J/token | valid |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for e in ENGINES:
        for c in r.energy[e].cycles:
            rows.append(f"| {ENGINE_LABELS[e]} | {c.file} | {c.health_percent:g} | {c.soc_start:g}→{c.soc_end:g} | {c.delta_soc:g} | "
                        f"{c.cycle_wall_s:.0f} | {c.tokens} | {c.gross_joules:.0f} | {c.implied_watts:.2f} | {c.idle_soc_scaled:.2f} | "
                        f"{c.net_joules:.0f} | {c.net_joules_per_token:.4f} | "
                        f"{('VALID' + (' (off-band start, any-start rule)' if c.off_band_start else '')) if c.valid else 'INVALID: ' + '; '.join(c.invalid_reasons)} |")
    rows += ["", "| engine | n valid | mean net J/token | spread (min–max) | systematic ± | implied W (mean) | status |", "|---|---|---|---|---|---|---|"]
    for e in ENGINES:
        en = r.energy[e]
        if en.headline:
            h = en.headline
            rows.append(f"| {ENGINE_LABELS[e]} | {h.n} | {h.mean_j_per_token:.4f} | {h.spread[0]:.4f}–{h.spread[1]:.4f} | "
                        f"±{100 * h.systematic_fraction:.1f}% | {h.implied_watts_mean:.2f} | headline |")
        else:
            rows.append(f"| {ENGINE_LABELS[e]} | {en.n_valid} | — | — | — | — | REFUSED: {'; '.join(en.refusals) or 'no valid cycles'} |")
    rows.append("")
    return rows


def _bandwidth_section(r: an.Report) -> list[str]:
    bw = r.bandwidth
    lines = ["## 5. Bandwidth pair (same build, same session)", ""]
    for k in ("triad", "read-only"):
        s = bw[k]
        lines.append(f"- {k}: median of {s.n} run(s) = {_fmt(s.median)} GB/s; run medians {', '.join(f'{v:.2f}' for v in s.values) or '—'}")
    ratios = bw.get("ratio_readonly_over_triad", [])
    lines.append("- paired read-only ÷ triad: " + (", ".join(f"{x:.3f}" for x in ratios) if ratios else "—"))
    lines.append("")
    return lines


def _roofline_section(r: an.Report) -> list[str]:
    lines = ["## 6. Roofline inputs (decode)", "",
             "| engine | window tok/s | bytes/token (weights + KV at window-median depth) | implied GB/s | triad GB/s | fraction |", "|---|---|---|---|---|---|"]
    for e, ro in r.roofline.items():
        lines.append(f"| {ENGINE_LABELS[e]} | {_fmt(ro.window_tok_s)} | {ro.bytes_per_token:,} | {_fmt(ro.implied_gbps)} | "
                     f"{_fmt(ro.denominator_gbps)} | {_fmt(ro.fraction_of_triad, 3)} |")
    lines.append("")
    return lines


def _refusal_ledger(r: an.Report) -> list[str]:
    lines = ["## 7. Refusals and notes", ""]
    lines += [f"- REFUSED: {x}" for x in r.refusals] or ["- no row refused"]
    for e in ENGINES:
        lines += [f"- {ENGINE_LABELS[e]} energy: {x}" for x in r.energy[e].refusals + r.energy[e].notes]
    lines += [f"- note: {x}" for x in r.notes]
    return lines
